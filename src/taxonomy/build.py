"""Generate ``publication/`` from ``data/``."""

from __future__ import annotations

from pathlib import Path

from taxonomy.load import load_dataset, load_registry
from taxonomy.render_markdown import render_chapters, render_single
from taxonomy.render_yaml import render_yaml

PUBLICATION = "publication"

README = """# publication/

Generated by `uv run taxonomy build` from `../data/`; do not edit by hand.
`uv run taxonomy build --check` (the `taxonomy-generated` hook) fails when
these files are stale.

- `engineering-best-practices.md`: the whole taxonomy in one Markdown file.
- `engineering-best-practices.yaml`: the same content as flattened YAML, with
  citations resolved to links and the source registry included.
- `chapters/`: the same Markdown split by numbered section, with stable rule
  anchors (`#p1`); start at [`chapters/README.md`](chapters/README.md).
"""


def generate(root: Path) -> dict[str, str]:
    """``{path relative to publication/: text}`` for every generated file."""
    ds = load_dataset(root)
    reg = load_registry(root)
    files = {
        "engineering-best-practices.md": render_single(ds, reg),
        "engineering-best-practices.yaml": render_yaml(ds, reg),
    }
    for name, text in render_chapters(ds, reg).items():
        files[f"chapters/{name}"] = text
    files["README.md"] = README
    return files


def existing(root: Path) -> dict[str, str]:
    base = root / PUBLICATION
    if not base.is_dir():
        return {}
    return {
        str(p.relative_to(base)): p.read_text(encoding="utf-8")
        for p in sorted(base.rglob("*"))
        if p.is_file()
        and not any(part.startswith(".") for part in p.relative_to(base).parts)
    }


def stale(root: Path) -> list[str]:
    """Paths (relative to ``publication/``) that are missing, differ or are extra."""
    want = generate(root)
    have = existing(root)
    out = [p for p in want if have.get(p) != want[p]]
    out += [p for p in have if p not in want]
    return sorted(out)


def write(root: Path) -> list[str]:
    """Write ``publication/`` and remove files no longer generated.

    Returns the changed paths.
    """
    want = generate(root)
    have = existing(root)
    base = root / PUBLICATION
    changed: list[str] = []
    for rel, text in want.items():
        if have.get(rel) != text:
            path = base / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("w", encoding="utf-8", newline="\n") as handle:
                handle.write(text)
            changed.append(rel)
    for rel in have:
        if rel not in want:
            (base / rel).unlink()
            changed.append(rel)
    # Remove directories the cleanup left empty (deepest first).
    for directory in sorted((d for d in base.rglob("*") if d.is_dir()), reverse=True):
        if not any(directory.iterdir()):
            directory.rmdir()
    return sorted(changed)

"""Render the flattened machine-readable YAML.

Top-level layout mirrors the edition-6 YAML (``meta``, ``categories``,
``domains``, ``domains_checked_without_row``, ``glossary``, ``rigor_matrix``,
``rules``, ``conflict_rules``) and adds ``sources``, ``quotes``, ``method``
and ``history``. Citations are resolved to ``[title](url)``; placeholder
quotes are dropped.
"""

from __future__ import annotations

import io
from collections.abc import Mapping
from typing import Any

from ruamel.yaml import YAML
from ruamel.yaml.scalarstring import LiteralScalarString

from taxonomy.model import Dataset, Source
from taxonomy.render_markdown import resolve_citations

HEADER = (
    "# Engineering Best Practices: machine-readable version.\n"
    "# Generated by `taxonomy build` from data/; do not edit.\n"
    "# Same IDs and wording as engineering-best-practices.md. Citations are resolved\n"
    "# to [title](url).\n\n"
)


def _resolve(
    value: Any, reg: Mapping[str, Source], titles: Mapping[str, str] | None
) -> Any:
    """Resolve citations in every string below ``value``."""
    if isinstance(value, str):
        text = resolve_citations(value, reg, titles)
        return LiteralScalarString(text) if "\n" in text else text
    if isinstance(value, list):
        return [_resolve(v, reg, titles) for v in value]
    if isinstance(value, dict):
        own = value.get("source_titles")
        use = {**(titles or {}), **own} if isinstance(own, dict) else titles
        return {
            k: _resolve(v, reg, use) for k, v in value.items() if k != "source_titles"
        }
    return value


def _refs(
    slugs: list[str], reg: Mapping[str, Source], titles: Mapping[str, str] | None
) -> Any:
    out = []
    for slug in slugs:
        src = reg[slug]
        out.append({"title": (titles or {}).get(slug, src["title"]), "url": src["url"]})
    return out


def build_document(ds: Dataset, reg: Mapping[str, Source]) -> dict[str, Any]:
    meta = dict(ds.meta)
    master = dict(meta["master_rule"])
    master["sources"] = _refs(master["sources"], reg, master.pop("source_titles", None))
    flat_meta = {
        "title": meta["title"],
        "edition": meta["edition"],
        "date": meta["date"],
        "master_rule": master,
        "sentence_structure": meta["sentence_structure"],
        "id_prefixes": meta["id_prefixes"],
        "classification_test": meta["classification_test"],
        "applicability_note": meta["applicability_note"],
        "quick_view_questions": meta["quick_view_questions"],
        "strength_keywords": meta["strength_keywords"],
        "relation_types": meta["relation_types"],
        "evidence_levels": meta["evidence_levels"],
        "known_exceptions": meta["known_exceptions"],
    }
    domains = []
    for d in ds.domains["domains"]:
        item = {
            k: v for k, v in d.items() if k not in ("references", "reference_titles")
        }
        item["references"] = _refs(d["references"], reg, d.get("reference_titles"))
        domains.append(item)
    rules = []
    for r in ds.rules:
        item = {
            k: v
            for k, v in r.items()
            if k not in ("sources", "source_titles", "management")
        }
        item["sources"] = _refs(r["sources"], reg, r.get("source_titles"))
        mg = r["management"]
        if mg:
            m = {k: v for k, v in mg.items() if k not in ("sources", "source_titles")}
            m["sources"] = _refs(mg["sources"], reg, mg.get("source_titles"))
            item["management"] = m
        else:
            item["management"] = None
        rules.append(item)
    quotes = []
    for q in ds.quotes:
        if q.get("placeholder"):
            continue
        item = {
            k: v
            for k, v in q.items()
            if k not in ("source", "extra_sources", "source_titles")
        }
        slugs = ([q["source"]] if q["source"] else []) + q.get("extra_sources", [])
        item["sources"] = _refs(slugs, reg, q.get("source_titles"))
        quotes.append(item)
    used = {s["slug"] for s in ds.sources}
    doc: dict[str, Any] = {
        "meta": flat_meta,
        "categories": ds.categories,
        "domains": domains,
        "domains_checked_without_row": ds.domains["checked_without_row"],
        "glossary": ds.glossary,
        "rigor_matrix": ds.rigor_matrix,
        "rules": rules,
        "conflict_rules": ds.conflicts,
        "quotes": quotes,
        "method": ds.method,
        "sources": [reg[s] for s in reg if s in used],
        "history": ds.history,
    }
    return _resolve(doc, reg, None)  # type: ignore[no-any-return]


def render_yaml(ds: Dataset, registry: Mapping[str, Source]) -> str:
    """The flattened YAML text (round-trip dumper, block style; never safe mode)."""
    yaml = YAML()
    yaml.default_flow_style = False
    yaml.width = 1_000_000
    yaml.indent(mapping=2, sequence=2, offset=0)
    yaml.allow_unicode = True
    buf = io.StringIO()
    yaml.dump(build_document(ds, registry), buf)
    text = "\n".join(line.rstrip() for line in buf.getvalue().split("\n"))
    return HEADER + text.rstrip("\n") + "\n"
